function jo(w, a, b){            /* 받침 있으면 a, 없으면 b */
  if(!w) return a;
  const c = w.charCodeAt(w.length-1);
  if (c < 0xAC00 || c > 0xD7A3) return a;
  return ((c - 0xAC00) % 28) ? a : b;
}
