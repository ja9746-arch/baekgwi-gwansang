/* ── 가리기 ─────────────────────────────────────── */
function readClues(F){
  const A = axes(F);
  const hit = [];
  for (const c of CLUE){
    const z = zOf(A, c.k) * c.d;
    if (z >= c.th) hit.push({ c, z, force: Math.min(3, z) });
  }
  /* 센 것부터 */
  hit.sort((a,b)=> b.z - a.z);

  /* 서로 맞버티는 것은 약한 쪽을 물립니다 —
     같은 자리에서 반대 방향이 함께 설 수는 없습니다. */
  const seen = new Set(), out = [];
  for (const h of hit){
    const key = h.c.k + "|" + (h.c.d>0 ? "+" : "-");
    const anti = h.c.k + "|" + (h.c.d>0 ? "-" : "+");
    if (seen.has(anti)) continue;
    seen.add(key); out.push(h);
  }

  /* 얼굴 하나에 열다섯은 서야 풀이가 섭니다.
     문턱에 못 미친 것 중 가장 가까운 것들을 끌어올립니다. */
  if (out.length < 15){
    const rest = [];
    for (const c of CLUE){
      if (out.find(h=>h.c.id===c.id)) continue;
      const z = zOf(A, c.k) * c.d;
      const anti = c.k + "|" + (c.d>0 ? "-" : "+");
      if (seen.has(anti)) continue;
      rest.push({ c, z, force: Math.max(0.4, Math.min(3, z)), near:true });
    }
    rest.sort((a,b)=> b.z - a.z);
    for (const r of rest){
      if (out.length >= 17) break;
      const key = r.c.k + "|" + (r.c.d>0 ? "+" : "-");
      if (seen.has(r.c.k + "|" + (r.c.d>0 ? "-" : "+"))) continue;
      seen.add(key); out.push(r);
    }
  }
  /* 너무 많아도 말이 흐려집니다 */
  const list = out.slice(0, 22);

  /* 첩별로 갈라 둡니다 */
  const byT = { 본성:[], 재물:[], 인연:[], 사회:[], 세월:[] };
  for (const h of list) for (const t of h.c.t) if (byT[t]) byT[t].push(h);
  for (const k in byT) byT[k].sort((a,b)=> b.z - a.z);

  const byBu = {};
  for (const h of list){ (byBu[h.c.bu] = byBu[h.c.bu] || []).push(h); }

  const gil = list.filter(h=>h.c.g>0), hyung = list.filter(h=>h.c.g<0);
  return { list, byT, byBu, gil, hyung, count: list.length, A };
}
