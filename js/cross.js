/* 십성 갈래가 걸린 얼굴 자리 */
const GRP_GUNG = { "재성":"재백", "관성":"관록", "식상":"남녀", "인성":"부모", "비겁":"형제" };

/* ── 교차 판정 ─────────────────────────────── */
function crossJudge(R, P){
  const t  = tally(P);
  const mv = moveSigns(P);
  const me = P.ilgan;

  /* 자리별 사주 쪽 세기 (0~3) */
  const ilji = tenGod(me, JIJANG[P.day.b]);
  const iljiGood = ["정재","정관","정인","식신","비견"].indexOf(ilji) >= 0;
  const sajuPow = {
    "연애": Math.max(strength(t.cnt["재성"] + t.cnt["관성"], t.total), iljiGood?2:0),
    "금전": strength(t.cnt["재성"], t.total),
    "직업": strength(t.cnt["관성"], t.total),
    "이동": Math.min(3, mv.yeokma + (mv.chung>0?1:0))
  };

  /* 얼굴 쪽 등급 (0 트임 / 1 반반 / 2 막힘) */
  const faceLv = {};
  CROSS.forEach(c=>{
    const j = R.jari.find(x=>x.g.k===c.gung);
    faceLv[c.k] = j ? j.lv : 1;
  });

  const rows = CROSS.map(c=>{
    const f = faceLv[c.k], s = sajuPow[c.k];
    let key;
    if(f===0 && s>=2)      key="겹";
    else if(f===0 && s<=1) key="그";
    else if(f===2 && s>=2) key="때";
    else if(f===2 && s<=1) key="둘";
    else                   key="반";
    const [t1,t2,t3] = CROSS_MAL[c.k][key];
    const j = R.jari.find(x=>x.g.k===c.gung);
    return { ...c, key, faceLv:f, sajuPow:s, title:t1, body:t2, act:t3,
             gungN: j?j.g.n:c.gung, bg: j?j.bg:null };
  });

  /* 올해 세운 */
  const thisYear = new Date().getFullYear();
  const ipc = ipchunJd(thisYear);
  const nowJd = toJd(thisYear, new Date().getMonth()+1, new Date().getDate(), 12, 0);
  const sy = nowJd < ipc ? thisYear-1 : thisYear;
  const syStem = SMOD(sy-4,10), syBr = SMOD(sy-4,12);
  const syGod  = GROUP[tenGod(me, syStem)];
  const [syT, syB] = SEUN_MAL[syGod];

  /* 가장 비어 있는 자리 — 거기 백귀가 하나 더 섭니다 */
  let weakGrp="재성", weakN=999;
  for(const g in t.cnt){ if(t.cnt[g] < weakN){ weakN=t.cnt[g]; weakGrp=g; } }
  const wGungK = GRP_GUNG[weakGrp];
  const wJari  = R.jari.find(x=>x.g.k===wGungK);
  const sajuSeed = SMOD(P.year.s*7 + P.month.b*13 + P.day.s*31 + P.day.b*17 + me*5, 2147483647);
  const pool = wJari ? wJari.g.pool.filter(x=>PICK3.every(p=>p.i!==x)) : [];
  const sajuBg = pool.length ? pickFrom(pool, sajuSeed, 3) : null;
  const 겹침 = (sajuBg!==null && R.boss.bg===sajuBg);

  /* 맞물림 — 얼굴의 그릇과 사주의 일간 오행 */
  const ilganOh = STEM[me][2];
  const hap = (ilganOh === R.hyeong) ? "같음"
            : (OH_SAENG[ilganOh] === R.hyeong) ? "생"
            : (OH_GEUK[ilganOh] === R.hyeong) ? "극"
            : (OH_SAENG[R.hyeong] === ilganOh) ? "설" : "반극";
  const hapMal = {
    "같음":"얼굴의 그릇과 사주의 일간이 같은 갈래입니다. 타고난 결이 한 방향이라, 되면 크게 되고 안 되면 크게 막힙니다.",
    "생":"사주의 일간이 얼굴의 그릇을 받칩니다. 손님은 타고난 것과 쓰는 것이 어긋나지 않습니다. 드문 짜임이에요.",
    "극":"사주의 일간이 얼굴의 그릇을 누릅니다. 겉으로 보이는 모습과 속으로 쓰는 힘이 다릅니다. 남들이 손님을 오해하는 이유가 여기 있습니다.",
    "설":"얼굴의 그릇이 사주 쪽으로 새고 있습니다. 가진 것을 밖으로 많이 내보내는 짜임이라, 쓰는 데가 늘 많습니다.",
    "반극":"얼굴의 그릇이 사주의 일간을 누릅니다. 겉이 속을 끌고 가는 짜임이라, 무리해서 해내고 뒤가 상합니다."
  }[hap];

  return {
    rows, t, mv,
    ilji, iljiGod: ilji,
    seun: { year: sy, stem: syStem, br: syBr, god: syGod, title: syT, body: syB,
            text: STEM[syStem][0]+BRANCH[syBr][0]+" "+STEM[syStem][1]+BRANCH[syBr][1] },
    weak: { grp: weakGrp, n: weakN, gungK: wGungK, gungN: wJari?wJari.g.n:"", bg: sajuBg },
    겹침, hap, hapMal,
    saju: sajuText(P)
  };
}
