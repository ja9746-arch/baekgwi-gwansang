const JARI_MAL = { "년":"어린 시절", "월":"사회에서의 자리",
                   "일":"손님과 배우자", "시":"말년" };
/* 지지끼리 걸린 것이 뜻하는 바 */
function relMal(kind, nm){
  const parts = nm ? nm.replace(/지/g,"").split("·") : [];
  const ws = parts.map(x=>JARI_MAL[x]).filter(Boolean);
  const where = ws.length===2 ? JO(ws[0],"과","와")+" "+ws[1] : ws.join(", ");
  if(kind==="충")  return (where?where+" 사이가 ":"")+"부딪칩니다. 그 자리는 한 번 흔들리고 나서 자리를 잡습니다.";
  if(kind==="합")  return (where?JO(where,"이","가")+" ":"")+"묶여 있습니다. 좋든 나쁘든 쉽게 떨어지지 않습니다.";
  if(kind==="형")  return "형이 걸렸습니다. 같은 일로 두 번 세 번 걸리는 자리입니다.";
  return "";
}
